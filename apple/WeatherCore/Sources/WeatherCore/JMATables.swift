    /// 緯度経度から府県予報区を選ぶ。名前が分かっていればコードを引き直します。
    public static func resolveOffice(lat: Double, lon: Double,
                                     officeNames: [String: String]? = nil) -> String {
        var best: (km: Double, name: String, code: String)?
        for o in offices {
            let km = Geo.distanceKm(lat, lon, o.lat, o.lon)
            if best == nil || km < best!.km {
                best = (km, o.name, o.code)
            }
        }
        guard let hit = best else { return "130000" }
        if let names = officeNames {
            for (code, name) in names where name == hit.name { return code }
        }
        return hit.code
    }

